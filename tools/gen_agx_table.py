"""Generate src/gpu/agx_table.rs: the instruction encodings of Apple's G13 GPU.

The table lists, for every instruction encoding that applegpu knows, the bit
pattern that identifies it and its two possible lengths. The kernel patcher
(src/gpu/patch.rs) uses it to walk compiled machine code instruction by
instruction; anything it cannot identify makes it leave the code unpatched.

usage: python3 -I tools/gen_agx_table.py PATH_TO_APPLEGPU > src/gpu/agx_table.rs

applegpu: https://github.com/dougallj/applegpu (BSD-3-Clause, Dougall Johnson).
"""
import os
import subprocess
import sys

root = sys.argv[1]
sys.path.insert(0, root)
import applegpu  # noqa: E402

commit = subprocess.run(["git", "-C", root, "rev-parse", "--short", "HEAD"],
                        capture_output=True, text=True).stdout.strip() or "unknown"
license_text = open(os.path.join(root, "LICENSE")).read().strip()

print(f"""// @generated by tools/gen_agx_table.py from applegpu {commit}. Do not edit.
//
// Instruction encodings of the Apple G13 GPU, derived from applegpu by
// Dougall Johnson (https://github.com/dougallj/applegpu), whose licence
// follows:
//""")
for line in license_text.splitlines():
    print(f"// {line}".rstrip())
print("""
/// One instruction encoding: it matches when `(word & mask) == bits`, where
/// `word` is the instruction truncated to its length, which is `sizes.1`
/// bytes if bit `length_bit` is set and `sizes.0` bytes otherwise.
pub struct Encoding {
    pub name: &'static str,
    pub mask: u128,
    pub bits: u128,
    pub sizes: (u8, u8),
    pub length_bit: u8,
}

/// In applegpu's order: the first matching entry identifies an instruction.
pub const ENCODINGS: &[Encoding] = &[""")
for d in applegpu.instruction_descriptors:
    print(f"    Encoding {{ name: {d.name!r}, mask: {d.mask:#x}, bits: {d.bits:#x}, "
          f"sizes: ({d.sizes[0]}, {d.sizes[1]}), length_bit: {d.length_bit_pos} }},".replace("'", '"'))
print("];")
